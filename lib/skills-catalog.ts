export const UNCATEGORIZED_ID = "weitere"

export function extractSpecialties(text: string): string[] {
  const hay = ` ${String(text || "").toLowerCase()} `
  const out: string[] = []
  const seen = new Set<string>()
  for (const sk of SKILL_CATALOG) {
    if (sk.id === "weitere") continue
    if (sk.names.some((n) => hay.includes(n.toLowerCase()))) {
      if (!seen.has(sk.id)) {
        seen.add(sk.id)
        out.push(sk.id)
      }
    }
  }
  if (out.length === 0) {
    const extra = SKILL_CATALOG.find((s) => s.id === "weitere")
    if (extra?.names.some((n) => hay.includes(n.toLowerCase()))) return ["weitere"]
    return ["weitere"]
  }
  return out
}

export function clusterById(id: string | null | undefined): SkillCluster | undefined {
  if (!id) return undefined
  return SKILL_CATALOG.find((s) => s.id === id)
}

export function specialtyLabel(id: string): string {
  if (id === "uncategorized") return "Weitere"
  return clusterById(id)?.label || id
}

export function specialtyNeedles(): { id: string; needle: string }[] {
  const out: { id: string; needle: string }[] = []
  for (const sk of SKILL_CATALOG) {
    if (sk.id === "weitere") continue
    for (const n of sk.names) out.push({ id: sk.id, needle: n.toLowerCase() })
  }
  return out
}
